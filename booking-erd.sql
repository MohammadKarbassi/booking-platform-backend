CREATE TABLE "users" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "phone" varchar(15) UNIQUE NOT NULL,
  "email" varchar(255) UNIQUE,
  "first_name" varchar(100),
  "last_name" varchar(100),
  "role" user_role NOT NULL DEFAULT 'guest',
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamp NOT NULL,
  "updated_at" timestamp
);

CREATE TABLE "otp_codes" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "phone" varchar(15) NOT NULL,
  "code_hash" varchar(255) NOT NULL,
  "expires_at" timestamp NOT NULL,
  "used_at" timestamp,
  "created_at" timestamp NOT NULL
);

CREATE TABLE "provinces" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(100) UNIQUE NOT NULL
);

CREATE TABLE "cities" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "province_id" int NOT NULL,
  "name" varchar(100) NOT NULL
);

CREATE TABLE "accommodation_types" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(50) UNIQUE NOT NULL,
  "slug" varchar(50) UNIQUE NOT NULL
);

CREATE TABLE "hosts" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" bigint UNIQUE,
  "full_name" varchar(150) NOT NULL,
  "phone" varchar(15) NOT NULL,
  "created_at" timestamp NOT NULL
);

CREATE TABLE "accommodations" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "host_id" bigint NOT NULL,
  "type_id" int NOT NULL,
  "city_id" int NOT NULL,
  "created_by" bigint NOT NULL,
  "title" varchar(200) NOT NULL,
  "slug" varchar(220) UNIQUE NOT NULL,
  "description" text,
  "address" text NOT NULL,
  "latitude" decimal(9,6) NOT NULL,
  "longitude" decimal(9,6) NOT NULL,
  "base_capacity" smallint NOT NULL,
  "max_capacity" smallint NOT NULL,
  "bedrooms" smallint NOT NULL DEFAULT 0,
  "beds" smallint NOT NULL DEFAULT 0,
  "bathrooms" smallint NOT NULL DEFAULT 0,
  "area_m2" int,
  "base_price_per_night" bigint NOT NULL,
  "extra_guest_price" bigint NOT NULL DEFAULT 0,
  "min_nights" smallint NOT NULL DEFAULT 1,
  "check_in_time" time NOT NULL,
  "check_out_time" time NOT NULL,
  "house_rules" text,
  "status" accommodation_status NOT NULL DEFAULT 'draft',
  "created_at" timestamp NOT NULL,
  "updated_at" timestamp
);

CREATE TABLE "accommodation_images" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "accommodation_id" bigint NOT NULL,
  "url" varchar(500) NOT NULL,
  "sort_order" smallint NOT NULL DEFAULT 0,
  "is_cover" boolean NOT NULL DEFAULT false
);

CREATE TABLE "amenities" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(100) UNIQUE NOT NULL,
  "icon" varchar(100)
);

CREATE TABLE "accommodation_amenities" (
  "accommodation_id" bigint,
  "amenity_id" int,
  PRIMARY KEY ("accommodation_id", "amenity_id")
);

CREATE TABLE "accommodation_calendar" (
  "accommodation_id" bigint,
  "date" date,
  "price_override" bigint,
  "is_blocked" boolean NOT NULL DEFAULT false,
  PRIMARY KEY ("accommodation_id", "date")
);

CREATE TABLE "bookings" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "booking_code" varchar(20) UNIQUE NOT NULL,
  "user_id" bigint NOT NULL,
  "accommodation_id" bigint NOT NULL,
  "check_in" date NOT NULL,
  "check_out" date NOT NULL,
  "guests_count" smallint NOT NULL,
  "total_price" bigint NOT NULL,
  "status" booking_status NOT NULL DEFAULT 'pending_payment',
  "expires_at" timestamp,
  "cancelled_at" timestamp,
  "created_at" timestamp NOT NULL
);

CREATE TABLE "booking_nights" (
  "booking_id" bigint NOT NULL,
  "accommodation_id" bigint NOT NULL,
  "night_date" date NOT NULL,
  "price" bigint NOT NULL,
  "pricing_rule_id" bigint,
  PRIMARY KEY ("accommodation_id", "night_date")
);

CREATE TABLE "payments" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "booking_id" bigint,
  "waitlist_request_id" bigint,
  "amount" bigint NOT NULL,
  "gateway" varchar(50) NOT NULL,
  "authority" varchar(100) UNIQUE,
  "ref_id" varchar(100) UNIQUE,
  "status" payment_status NOT NULL DEFAULT 'initiated',
  "paid_at" timestamp,
  "refunded_at" timestamp,
  "created_at" timestamp NOT NULL
);

CREATE TABLE "waitlist_requests" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" bigint NOT NULL,
  "accommodation_id" bigint NOT NULL,
  "check_in" date NOT NULL,
  "check_out" date NOT NULL,
  "guests_count" smallint NOT NULL,
  "held_amount" bigint NOT NULL,
  "status" waitlist_status NOT NULL DEFAULT 'waiting',
  "expires_at" timestamp NOT NULL,
  "booking_id" bigint UNIQUE,
  "created_at" timestamp NOT NULL
);

CREATE TABLE "poi_categories" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(50) UNIQUE NOT NULL
);

CREATE TABLE "points_of_interest" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "category_id" int NOT NULL,
  "city_id" int NOT NULL,
  "name" varchar(200) NOT NULL,
  "latitude" decimal(9,6) NOT NULL,
  "longitude" decimal(9,6) NOT NULL,
  "description" text
);

CREATE TABLE "holidays" (
  "date" date PRIMARY KEY,
  "title" varchar(150) NOT NULL,
  "is_official" boolean NOT NULL DEFAULT true
);

CREATE TABLE "pricing_rules" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "accommodation_id" bigint NOT NULL,
  "rule_type" pricing_rule_type NOT NULL,
  "adjustment_type" adjustment_type NOT NULL,
  "value" int NOT NULL,
  "start_date" date,
  "end_date" date,
  "min_nights" smallint,
  "days_before_checkin" smallint,
  "priority" smallint NOT NULL DEFAULT 0,
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamp NOT NULL
);

CREATE TABLE "reviews" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "booking_id" bigint UNIQUE NOT NULL,
  "rating" smallint NOT NULL,
  "comment" text,
  "status" review_status NOT NULL DEFAULT 'pending',
  "admin_reply" text,
  "created_at" timestamp NOT NULL
);

CREATE TABLE "favorites" (
  "user_id" bigint,
  "accommodation_id" bigint,
  "created_at" timestamp NOT NULL,
  PRIMARY KEY ("user_id", "accommodation_id")
);

